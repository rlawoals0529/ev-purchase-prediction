"""Build conservative rank-blend hedges from our own source-allTE and high-res models.

This script does not train or import third-party predictions. It combines two
submission files generated by this repository. The primary model is the
validated source-support + all-column-TE LightGBM; the secondary model is the
older high-resolution additive LightGBM that previously added diversity to the
engineered XGBoost family.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import rankdata

TARGET = "Will_Buy_EV"


def rank01(x: np.ndarray) -> np.ndarray:
    return (rankdata(x, method="average") - 0.5) / len(x)


def lex_unique(primary: np.ndarray, source: np.ndarray, secondary: np.ndarray, ids: np.ndarray) -> np.ndarray:
    """Break only exact primary-score ties; preserve every non-tied ordering."""
    order = np.lexsort((ids, secondary, source, primary))
    out = np.empty(len(primary), dtype=np.float64)
    out[order] = (np.arange(len(primary)) + 0.5) / len(primary)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True)
    ap.add_argument("--highres", required=True)
    ap.add_argument("--output-dir", default="submissions")
    ap.add_argument("--weights", nargs="+", type=float, default=[0.90, 0.85],
                    help="Weight on source-allTE; remainder goes to high-res")
    args = ap.parse_args()

    source = pd.read_csv(args.source)
    highres = pd.read_csv(args.highres)
    if not source.id.equals(highres.id):
        raise ValueError("submission id order differs")

    rs = rank01(source[TARGET].to_numpy())
    rh = rank01(highres[TARGET].to_numpy())
    outdir = Path(args.output_dir)
    outdir.mkdir(parents=True, exist_ok=True)

    for w in args.weights:
        if not 0 <= w <= 1:
            raise ValueError(f"invalid source weight {w}")
        primary = w * rs + (1 - w) * rh
        pred = lex_unique(
            primary,
            source[TARGET].to_numpy(),
            highres[TARGET].to_numpy(),
            source.id.to_numpy(),
        )
        tag = f"{round(100*w)}_{round(100*(1-w))}"
        path = outdir / f"candidate_sourceallte_highres_rank_{tag}_lex.csv"
        pd.DataFrame({"id": source.id, TARGET: pred}).to_csv(path, index=False)
        print(path, "rows", len(pred), "unique", len(np.unique(pred)))


if __name__ == "__main__":
    main()
